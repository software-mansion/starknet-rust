//! Run against a fresh `starknet-devnet` 0.7.2 started with `--seed 190 --port 5190`.
//! `ETH_ACCOUNT_SIERRA` points to the `starknet.js` account artifact pinned in the test workflow.
#![cfg(feature = "eth")]

use starknet_rust::{
    accounts::{Account, ConnectedAccount, EncodedAccount, ExecutionEncoding, SingleOwnerAccount},
    contract::{ContractFactory, UdcSelector},
    core::{
        chain_id,
        types::{Call, ExecutionResult, Felt, contract::SierraClass},
    },
    macros::{felt, selector},
    providers::{JsonRpcClient, Provider, jsonrpc::HttpTransport},
    signers::{EthSigner, LocalWallet, SigningKey},
};

#[tokio::test]
#[ignore = "requires fresh local devnet and ETH_ACCOUNT_SIERRA"]
async fn deployed_eth_account_executes_transfer() {
    let provider = JsonRpcClient::new(HttpTransport::new(
        "http://127.0.0.1:5190/rpc".parse::<url::Url>().unwrap(),
    ));
    // Public devnet fixture generated by --seed 190.
    let funder = SingleOwnerAccount::new(
        &provider,
        LocalWallet::from(SigningKey::from_secret_scalar(felt!(
            "0x5ccb142f4032c1234b2531e32f346e6e"
        ))),
        felt!("0xe8def5667c629989143bcdb2f542b382b533fe5c13769c5dfc288ab3a65b12"),
        chain_id::SEPOLIA,
        ExecutionEncoding::New,
    );
    let artifact = std::fs::File::open(std::env::var("ETH_ACCOUNT_SIERRA").unwrap()).unwrap();
    let class: SierraClass = serde_json::from_reader(artifact).unwrap();
    // Compiled class hash for the pinned Sierra artifact on devnet 0.7.2.
    let compiled_hash = felt!("0x69c95fea1edb4a31168fca667890988b95d7ddfd5abeb1eb5482912b1f478e4");
    let class_hash = funder
        .declare_v3(class.flatten().unwrap().into(), compiled_hash)
        .send()
        .await
        .unwrap()
        .class_hash;

    let signer = EthSigner::from_bytes(&[1; 32]).unwrap();
    // Cairo serializes the secp256k1 point as (x.low, x.high, y.low, y.high).
    let key = signer.public_key();
    let constructor =
        [&key[16..32], &key[..16], &key[48..], &key[32..48]].map(Felt::from_bytes_be_slice);
    let factory = ContractFactory::new_with_udc(class_hash, &funder, UdcSelector::New);
    let deployment = factory.deploy_v3(constructor.to_vec(), Felt::ONE, false);
    let address = deployment.deployed_address();
    deployment.send().await.unwrap();

    let token = felt!("0x4718f5a0fc34cc1af16a1cdee98ffb20c31f5cd61d6ab07201858f4287c938d");
    let transfer = |recipient, amount| Call {
        to: token,
        selector: selector!("transfer"),
        calldata: vec![recipient, amount, Felt::ZERO],
    };
    funder
        .execute_v3(vec![transfer(address, Felt::from(10u64.pow(18)))])
        .send()
        .await
        .unwrap();

    let account = EncodedAccount::new(
        &provider,
        signer,
        address,
        chain_id::SEPOLIA,
        ExecutionEncoding::New,
    );
    let result = account
        .execute_v3(vec![transfer(funder.address(), Felt::ONE)])
        .send()
        .await
        .unwrap();
    let receipt = provider
        .get_transaction_receipt(result.transaction_hash)
        .await
        .unwrap();
    assert_eq!(
        receipt.receipt.execution_result(),
        &ExecutionResult::Succeeded
    );
    assert_eq!(account.get_nonce().await.unwrap(), Felt::ONE);
}
